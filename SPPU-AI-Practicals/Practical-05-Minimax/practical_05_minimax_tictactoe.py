"""Practical 5: Minimax algorithm for a two-player deterministic game (Tic-Tac-Toe).

X is the maximizer (+1); O is the minimizer (-1). The board is indexed 0..8.
"""

WIN_LINES = [
    (0, 1, 2), (3, 4, 5), (6, 7, 8),
    (0, 3, 6), (1, 4, 7), (2, 5, 8),
    (0, 4, 8), (2, 4, 6),
]


def winner(board):
    for a, b, c in WIN_LINES:
        if board[a] == board[b] == board[c] and board[a] != " ":
            return board[a]
    return None


def minimax(board, is_maximizing):
    result = winner(board)
    if result == "X":
        return 1
    if result == "O":
        return -1
    if " " not in board:
        return 0

    if is_maximizing:
        best = float("-inf")
        for i in range(9):
            if board[i] == " ":
                board[i] = "X"
                score = minimax(board, False)
                board[i] = " "  # undo the trial move
                best = max(best, score)
        return best

    best = float("inf")
    for i in range(9):
        if board[i] == " ":
            board[i] = "O"
            score = minimax(board, True)
            board[i] = " "  # undo the trial move
            best = min(best, score)
    return best


def best_move(board):
    best_score = float("-inf")
    selected = None
    for i in range(9):
        if board[i] == " ":
            board[i] = "X"
            score = minimax(board, False)
            board[i] = " "
            if score > best_score:
                best_score, selected = score, i
    return selected, best_score


def print_board(board):
    for r in range(0, 9, 3):
        print(" | ".join(board[r:r + 3]))
        if r < 6:
            print("---------")


def main():
    # Demonstration state: X can win immediately by placing at cell 7 (1-based).
    board = ["X", "O", "X", "O", "X", " ", " ", " ", "O"]
    print("Current Tic-Tac-Toe board:")
    print_board(board)
    move, score = best_move(board)
    if move is None:
        print("No legal move available.")
    else:
        print(f"Best move for X: cell {move + 1}")
        print("Minimax score:", score)


if __name__ == "__main__":
    main()
